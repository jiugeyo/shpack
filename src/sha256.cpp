void Sha256::reset() {
    h_[0] = 0x6a09e667u; h_[1] = 0xbb67ae85u; h_[2] = 0x3c6ef372u; h_[3] = 0xa54ff53au;
    h_[4] = 0x510e527fu; h_[5] = 0x9b05688cu; h_[6] = 0x1f83d9abu; h_[7] = 0x5be0cd19u;
    bits_ = 0;
    used_ = 0;
    std::memset(buf_, 0, sizeof(buf_));
}

void Sha256::block(const uint8_t* p) {
    uint32_t w[64];
    for (int i = 0; i < 16; ++i) w[i] = load_be32(p + i * 4);
    for (int i = 16; i < 64; ++i) {
        uint32_t s0 = rotr(w[i - 15], 7) ^ rotr(w[i - 15], 18) ^ (w[i - 15] >> 3);
        uint32_t s1 = rotr(w[i - 2], 17) ^ rotr(w[i - 2], 19) ^ (w[i - 2] >> 10);
        w[i] = w[i - 16] + s0 + w[i - 7] + s1;
    }

    uint32_t a = h_[0], b = h_[1], c = h_[2], d = h_[3];
    uint32_t e = h_[4], f = h_[5], g = h_[6], h = h_[7];
    for (int i = 0; i < 64; ++i) {
        uint32_t S1 = rotr(e, 6) ^ rotr(e, 11) ^ rotr(e, 25);
        uint32_t ch = (e & f) ^ (~e & g);
        uint32_t t1 = h + S1 + ch + K[i] + w[i];
        uint32_t S0 = rotr(a, 2) ^ rotr(a, 13) ^ rotr(a, 22);
        uint32_t maj = (a & b) ^ (a & c) ^ (b & c);
        uint32_t t2 = S0 + maj;
        h = g; g = f; f = e; e = d + t1;
        d = c; c = b; b = a; a = t1 + t2;
    }
    h_[0] += a; h_[1] += b; h_[2] += c; h_[3] += d;
    h_[4] += e; h_[5] += f; h_[6] += g; h_[7] += h;
}

void Sha256::update(const void* data, size_t len) {
    const uint8_t* p = static_cast<const uint8_t*>(data);
    bits_ += static_cast<uint64_t>(len) * 8;
    while (len > 0) {
        size_t take = 64 - used_;
        if (take > len) take = len;
        std::memcpy(buf_ + used_, p, take);
        used_ += take;
        p += take;
        len -= take;
        if (used_ == 64) {
            block(buf_);
            used_ = 0;
        }
    }
}

void Sha256::final(uint8_t out[32]) {
    uint8_t pad[72];
    std::memset(pad, 0, sizeof(pad));
    pad[0] = 0x80;
    size_t padlen = (used_ < 56) ? (56 - used_) : (120 - used_);
    uint64_t bits = bits_;
    update(pad, padlen);
    uint8_t lenbuf[8];
    for (int i = 0; i < 8; ++i) lenbuf[i] = static_cast<uint8_t>(bits >> (56 - 8 * i));
    update(lenbuf, 8);
    for (int i = 0; i < 8; ++i) store_be32(out + i * 4, h_[i]);
}

void sha256(const void* data, size_t len, uint8_t out[32]) {
    Sha256 s;
    s.update(data, len);
    s.final(out);
}

void sha256_hex(const void* data, size_t len, char out[65]) {
    uint8_t d[32];
    sha256(data, len, d);
    static const char* hexd = "0123456789abcdef";
    for (int i = 0; i < 32; ++i) {
        out[i * 2] = hexd[d[i] >> 4];
        out[i * 2 + 1] = hexd[d[i] & 0x0f];
    }
    out[64] = '\0';
}

